amount=(int(input("Enter a number from user")))
if amount>25000:
    Discount=0.1
elif amount>20000:
    Discount=0.008
elif amount>15000:
    Discount=0.05
elif amount>10000:
    Discount=0.03
else :
    Discount=0
print(f"Amount:{amount}")
print(f"Discount:{amount*Discount}")
print(f"Total:{amount-(amount*Discount)}")

